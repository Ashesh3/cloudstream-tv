import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { transformTvAstryxCss } from "./astryx-css-compat.mjs";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const corePath = require.resolve("@astryxdesign/core/astryx.css");
const themePath = resolve(repoRoot, "packages/theme/dist/cloudframe-night.css");
const outputPath = resolve(repoRoot, "packages/theme/dist/cloudframe-night.tv.css");
const check = process.argv.includes("--check");

const [coreCss, themeCss] = await Promise.all([
  readFile(corePath, "utf8"),
  readFile(themePath, "utf8")
]);
const header = `/*\n * @generated by \`node scripts/build-tv-astryx-css.mjs\` — do not edit manually.\n * Core: @astryxdesign/core@0.5.1\n * Theme: packages/theme/dist/cloudframe-night.css\n */\n\n`;
const output = header + transformTvAstryxCss({ coreCss, themeCss });

if (check) {
  let current = null;
  try {
    current = await readFile(outputPath, "utf8");
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  if (current !== output) {
    throw new Error("TV Astryx CSS is missing or stale; run npm run build:theme");
  }
  console.log("TV Astryx CSS is up to date.");
} else {
  await writeFile(outputPath, output);
  console.log(`Built ${outputPath}`);
}
